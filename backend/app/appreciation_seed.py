def store_appreciation_refs(db: Session) -> int:
    """幂等入库赏析范文。返回新增数量。"""
    existing = {r.title for r in db.query(models.AppreciationRef).all()}
    added = 0
    for ex in APPRECIATION_EXAMPLES:
        if ex["title"] in existing:
            continue
        db.add(
            models.AppreciationRef(
                title=ex["title"],
                author=ex["author"],
                kind=ex["kind"],
                content=ex["content"],
            )
        )
        added += 1
    db.commit()
    return added
