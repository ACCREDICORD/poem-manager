def seed_templates(db: Session) -> int:
    """幂等：仅插入不存在的词牌/诗体，返回新增数量。"""
    existing = {t.name for t in db.query(models.Template).all()}
    added = 0
    for t in PRESET_TEMPLATES:
        if t["name"] in existing:
            continue
        data = dict(t)
        data["line_count"] = len(data["pattern"])
        data["editable"] = True
        db.add(models.Template(**data))
        added += 1
    db.commit()
    return added
